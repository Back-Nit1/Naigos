"""A tiny synthetic urban-obstacle artifact for contract tests.

Nothing here is real geometry: a 24 x 16 grid at 10 m with one tower, one slab, a no-data strip
and a protected-zone exclusion, over a made-up AOI. ``python tests/_urban_fixtures.py``
regenerates the committed copy under ``tests/fixtures/urban_physics/`` (deterministic).
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
FIXTURE_ROOT = REPO / "tests" / "fixtures"
AOI_NAME = "synthetic_test"
AOI_BOUNDS = (-74.10, 40.60, -73.90, 40.80)
PHYSICS_BOUNDS = (-74.02, 40.70, -74.00, 40.72)
UTM_EPSG = 32618
NX, NY, CELL = 24, 16, 10.0


def aoi_fingerprint() -> str:
    raw = ",".join(f"{v:.6f}" for v in (AOI_BOUNDS[0], AOI_BOUNDS[1], AOI_BOUNDS[2], AOI_BOUNDS[3]))
    return hashlib.sha256(raw.encode()).hexdigest()[:10]


def _source(role: str, key: str):
    from naigos.data.urban_obstacles import UrbanSource

    return UrbanSource(
        key=key, name=f"synthetic {role}", product_id=f"synthetic-{role}-v1", role=role,
        licence="CC0 (generated in-repo for tests)", licence_url="https://creativecommons.org/publicdomain/zero/1.0/",
        citation="Synthetic test data generated by tests/_urban_fixtures.py.",
        url="https://example.invalid/synthetic", captured="2000-01-01", published="2000-01-02",
        retrieved="2000-01-03T00:00:00Z", sha256=hashlib.sha256(key.encode()).hexdigest(),
        redistribution="repository")


def make_meta(**over):
    from pyproj import Transformer

    from naigos.data.urban_obstacles import BuildInfo, Exclusion, UrbanObstacleMeta

    tf = Transformer.from_crs("EPSG:4326", f"EPSG:{UTM_EPSG}", always_xy=True)
    back = Transformer.from_crs(f"EPSG:{UTM_EPSG}", "EPSG:4326", always_xy=True)
    e0, n0 = tf.transform((PHYSICS_BOUNDS[0] + PHYSICS_BOUNDS[2]) / 2, (PHYSICS_BOUNDS[1] + PHYSICS_BOUNDS[3]) / 2)
    env_origin = (round(e0 - 5000.0), round(n0 - 5000.0))
    gx, gy = 4990.0, 4990.0  # SW corner of the grid, ENU relative to the env origin
    corners = tuple(tuple(round(v, 6) for v in back.transform(env_origin[0] + x, env_origin[1] + y))
                    for x, y in ((gx, gy), (gx + NX * CELL, gy), (gx + NX * CELL, gy + NY * CELL), (gx, gy + NY * CELL)))
    kw = dict(
        aoi_name=AOI_NAME, aoi_fingerprint=aoi_fingerprint(), aoi_bounds_wgs84=AOI_BOUNDS,
        physics_bounds_wgs84=PHYSICS_BOUNDS, grid_corners_wgs84=corners, utm_epsg=UTM_EPSG,
        env_origin_utm_m=(float(env_origin[0]), float(env_origin[1])), grid_origin_enu_m=(gx, gy),
        cell_m=CELL, nx=NX, ny=NY,
        sources=(_source("ground", "synthetic_ground"), _source("structures", "synthetic_structures")),
        build=BuildInfo("unknown", False, "2000-01-04T00:00:00Z"),
        uncertainty_present=True, uncertainty_kind="synthetic 1-sigma height, metres",
        exclusions=(Exclusion("synthetic protected zone", (-74.0195, 40.7005, -74.0190, 40.7010), 6),),
        notes="synthetic fixture; not real geometry",
    )
    kw.update(over)
    return UrbanObstacleMeta(**kw)


def make_arrays():
    ground = (10.0 + 0.05 * np.add.outer(np.arange(NY), np.arange(NX))).astype(np.float32)
    top = ground.copy()
    cov = np.ones((NY, NX), np.uint8)
    bld = np.zeros((NY, NX), np.uint8)
    top[4:7, 5:8] += 80.0  # a tower
    bld[4:7, 5:8] = 1
    top[10:12, 12:20] += 25.0  # a slab
    bld[10:12, 12:20] = 1
    cov[:, 22:] = 0  # a no-data strip on the east edge
    cov[0, 0:3] = 0
    cov[1, 0:3] = 0  # excluded cells: 6 (+ strip)
    unc = np.full((NY, NX), 1.5, np.float32)
    for a in (ground, top, unc):
        a[cov == 0] = np.nan
    return dict(ground_amsl_m=ground, top_amsl_m=top, coverage=cov, building=bld, uncertainty_m=unc)


def make_grid(**meta_over):
    from naigos.data.urban_obstacles import build_urban_obstacle_grid

    return build_urban_obstacle_grid(make_meta(**meta_over), **make_arrays())


def committed_dir() -> Path:
    from naigos.data.urban_obstacles import artifact_dir

    return artifact_dir(FIXTURE_ROOT / "urban_physics_root", AOI_NAME, make_grid().hashes.content_sha256)


if __name__ == "__main__":
    from naigos.data.urban_obstacles import write_urban_obstacles

    print(write_urban_obstacles(make_grid(), FIXTURE_ROOT / "urban_physics_root"), file=sys.stderr)
